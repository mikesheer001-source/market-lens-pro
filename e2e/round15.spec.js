import {test,expect} from '@playwright/test';
import {sampleData} from '../src/engine.js';

test('Round 15: single, equal-weight and best-fit use selected dates, show real strategy attribution',async ({page})=>{
  test.setTimeout(180000);
  const prices=sampleData()['DEMO-SPY'];
  const start=prices[300].time,end=prices[800].time;
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('./');
  await page.locator('[data-option="preset"]').selectOption('all');
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await expect(page.locator('[data-option="portfolio-mode"]')).toHaveValue('single');
  await expect(page.locator('[data-bt-range="startDate"]')).toHaveValue('');
  await expect(page.locator('[data-bt-range="endDate"]')).toHaveValue('');
  await page.locator('[data-bt-range="startDate"]').fill(start);
  await page.locator('[data-bt-range="endDate"]').fill(end);
  await page.locator('[data-action="run-backtest"]').click();
  await expect(page.locator('#backtest-result-range')).toContainText('Selected range: '+start+' to '+end);
  await expect(page.locator('#backtest-result-range')).toContainText('actual bars');
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  await page.locator('[data-option="portfolio-mode"]').selectOption('portfolio');
  await page.locator('[data-action="run-portfolio"]').click();
  await expect(page.locator('#portfolio-source')).toContainText('Selected range: '+start+' to '+end);
  await expect(page.locator('#portfolio-breakdown tbody tr')).toHaveCount(4);
  await expect(page.locator('#portfolio-breakdown tbody tr').first()).toContainText('DEMO');
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  await page.locator('[data-option="portfolio-mode"]').selectOption('best-fit');
  await expect(page.locator('[data-action="run-best-fit"]')).toBeVisible();
  await page.locator('[data-action="run-best-fit"]').click();
  await expect(page.locator('#portfolio-source')).toContainText('Saved best-fit portfolio',{timeout:150000});
  await expect(page.locator('#portfolio-source')).toContainText('Selected range: '+start+' to '+end);
  await expect(page.locator('#portfolio-breakdown tbody tr').first()).toContainText('Fit Sharpe:');
  await expect(page.locator('#portfolio-breakdown')).toContainText('Strategy');
  await expect(page.locator('#portfolio-methodology')).toContainText('selection bias');
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  expect(errors).toEqual([]);
});
test('Round 15: reversed and empty single-symbol windows refuse to trade with plain messages',async ({page})=>{
  const prices=sampleData()['DEMO-SPY'];
  await page.goto('./');
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await page.locator('[data-bt-range="startDate"]').fill(prices[400].time);
  await page.locator('[data-bt-range="endDate"]').fill(prices[300].time);
  await page.locator('[data-action="run-backtest"]').click();
  await expect(page.locator('#backtest-range-error')).toContainText('start date must be on or before');
  await expect(page.locator('#equity-chart')).toHaveCount(0);
  await page.locator('[data-bt-range="startDate"]').fill('2099-01-01');
  await page.locator('[data-bt-range="endDate"]').fill('');
  await page.locator('[data-action="run-backtest"]').click();
  await expect(page.locator('#backtest-range-error')).toContainText('No bars fall inside');
  await page.locator('[data-action="clear-bt-dates"]').click();
  await expect(page.locator('[data-bt-range="startDate"]')).toHaveValue('');
  await expect(page.locator('[data-bt-range="endDate"]')).toHaveValue('');
});
