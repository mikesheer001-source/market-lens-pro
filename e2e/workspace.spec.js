test('named watchlists and symbols can be created, renamed, selected and deleted',async ({page})=>{
  await page.goto('./');
  await page.locator('[data-input="watchlist-name"]').fill('Volatility candidates');
  await page.locator('[data-action="watchlist-create"]').click();
  await expect(page.locator('[data-option="watchlist-select"] option')).toHaveCount(2);
  await page.locator('tr[data-symbol="VXX"] button.star').click();
  await expect(page.locator('tr[data-symbol="VXX"] button.star')).toHaveClass(/on/);
  await page.locator('[data-option="watchlist-select"]').selectOption('default');
  await expect(page.locator('tr[data-symbol="VXX"] button.star')).not.toHaveClass(/on/);
  const created=await page.locator('[data-option="watchlist-select"] option').last().getAttribute('value');
  await page.locator('[data-option="watchlist-select"]').selectOption(created);
  await expect(page.locator('tr[data-symbol="VXX"] button.star')).toHaveClass(/on/);
  await page.locator('[data-input="watchlist-name"]').fill('My volatility');
  await page.locator('[data-action="watchlist-rename"]').click();
  await expect(page.locator('[data-option="watchlist-select"] option').last()).toContainText('My volatility');
  await page.reload();
  await expect(page.locator('[data-option="watchlist-select"] option')).toHaveCount(2);
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-action="watchlist-delete"]').click();
  await expect(page.locator('[data-option="watchlist-select"] option')).toHaveCount(1);
});

test('saved scan restores exact rule set and archived filtered rows after reload',async ({page})=>{
  await page.goto('./');
  await page.locator('[data-option="preset"]').selectOption('oversold');
  await page.locator('[data-option="matches"]').check();
  await expect(page.locator('tbody tr[data-symbol]')).toHaveCount(1);
  await page.locator('[data-input="scan-name"]').fill('RSI oversold');
  await page.locator('[data-action="save-scan"]').click();
  await expect(page.locator('[data-option="saved-scan-select"] option')).toHaveCount(2);
  await page.locator('[data-option="preset"]').selectOption('all');
  await expect(page.locator('tbody tr[data-symbol]')).toHaveCount(4); // no rules: every symbol is a match
  await page.locator('[data-option="matches"]').uncheck();
  await expect(page.locator('tbody tr[data-symbol]')).toHaveCount(4);
  const id=await page.locator('[data-option="saved-scan-select"] option').last().getAttribute('value');
  await page.locator('[data-option="saved-scan-select"]').selectOption(id);
  await expect(page.locator('tbody tr[data-symbol]')).toHaveCount(1);
  await expect(page.locator('tbody tr[data-symbol="COIN"]')).toBeVisible();
  await expect(page.getByText(/Showing saved scan snapshot:/)).toContainText('archived values');
  await page.reload();
  await page.locator('[data-option="saved-scan-select"]').selectOption(id);
  await expect(page.locator('tbody tr[data-symbol="COIN"]')).toBeVisible();
});

test('local price and RSI alerts are evaluated on each scan and persist until dismissed',async ({page})=>{
  await page.goto('./');
  await expect(page.locator('[data-alert-field="symbol"] option[value="VXX"]')).toHaveCount(1);
  await page.locator('[data-alert-field="symbol"]').selectOption('VXX');
  await page.locator('[data-alert-field="metric"]').selectOption('price');
  await page.locator('[data-alert-field="op"]').selectOption('>');
  await page.locator('[data-alert-field="threshold"]').fill('0');
  await page.locator('[data-action="alert-create"]').click();
  await expect(page.locator('.toast')).toContainText('Alert added');
  const response=page.waitForResponse('**/api/stocks/scan?**');
  await page.locator('[data-action="scan-universe"]').click();
  await response;
  await expect(page.locator('#scan-status')).toContainText('Live scan complete');
  await expect(page.locator('.alert-banner')).toContainText('VXX');
  await expect(page.locator('.alert-banner')).toContainText('1 in-app alert triggered');
  await page.reload();
  await expect(page.locator('.alert-banner')).toBeVisible();
  await page.locator('[data-action="alert-ack"]').click();
  await expect(page.locator('.alert-banner')).toHaveCount(0);
});

test('Chart Lab workspaces collapse independently without losing settings or archived scans',async ({page})=>{
  await page.goto('./');
  await page.locator('[data-option="preset"]').selectOption('oversold');
  await page.locator('[data-option="matches"]').check();
  await expect(page.locator('tbody tr[data-symbol="COIN"]')).toBeVisible();
  await page.locator('.sidebar [data-tab="charts"]').click();
  const workspaces=page.locator('#chart-workspaces');
  const watch=workspaces.locator('[data-workspace-section="watchlists"]');
  const scans=workspaces.locator('[data-workspace-section="scans"]');
  const alerts=workspaces.locator('[data-workspace-section="alerts"]');
  await expect(workspaces.locator(':scope > details')).toHaveCount(9);
  expect(await workspaces.evaluate(el=>Boolean(document.querySelector('#chart-lab-panel').compareDocumentPosition(el)&Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  await expect(workspaces.locator(':scope > details[open]')).toHaveCount(0);
  await expect(page.locator('#price-chart canvas').first()).toBeVisible();
  await page.locator('#price-chart').evaluate(el=>el.dataset.retained='yes');
  await watch.locator('summary').click();
  await scans.locator('summary').click();
  await alerts.locator('summary').click();
  await expect(workspaces.locator(':scope > details[open]')).toHaveCount(3);
  await watch.getByLabel('Watchlist name').fill('Chart candidates');
  await scans.getByLabel('Scan name').fill('Chart archive');
  await alerts.locator('[data-alert-field="symbol"]').selectOption('VXX');
  await alerts.locator('[data-alert-field="metric"]').selectOption('rsi');
  await alerts.locator('[data-alert-field="op"]').selectOption('<');
  await alerts.getByLabel('Level').fill('42');
  await scans.locator('summary').click();
  await expect(scans.getByLabel('Scan name')).toBeHidden();
  await expect(watch.getByLabel('Watchlist name')).toBeVisible();
  await expect(alerts.getByLabel('Level')).toBeVisible();
  await watch.locator('summary').click();
  await alerts.locator('summary').click();
  await expect(workspaces.locator(':scope > details[open]')).toHaveCount(0);
  await watch.locator('summary').press('Enter');
  await scans.locator('summary').click();
  await alerts.locator('summary').click();
  await expect(watch.getByLabel('Watchlist name')).toHaveValue('Chart candidates');
  await expect(scans.getByLabel('Scan name')).toHaveValue('Chart archive');
  await expect(alerts.locator('[data-alert-field="symbol"]')).toHaveValue('VXX');
  await expect(alerts.locator('[data-alert-field="metric"]')).toHaveValue('rsi');
  await expect(alerts.locator('[data-alert-field="op"]')).toHaveValue('<');
  await expect(alerts.getByLabel('Level')).toHaveValue('42');
  await expect(page.locator('#price-chart')).toHaveAttribute('data-retained','yes');
  await watch.getByRole('button',{name:'Create watchlist'}).click();
  await expect(watch.locator('select option:checked')).toContainText('Chart candidates');
  await expect(scans.getByLabel('Scan name')).toHaveValue('Chart archive');
  await expect(alerts.getByLabel('Level')).toHaveValue('42');
  await alerts.getByRole('button',{name:'Add alert'}).click();
  await expect(alerts.locator('.data-list')).toContainText('VXX RSI below 42');
  await scans.getByRole('button',{name:'Save scan',exact:true}).click();
  await expect(scans.locator('select option:checked')).toContainText('Chart archive · 1 rows');
  await alerts.locator('summary').click();
  await page.reload();
  await expect(watch).toHaveAttribute('open','');
  await expect(scans).toHaveAttribute('open','');
  await expect(alerts).not.toHaveAttribute('open','');
  await expect(watch.locator('select option:checked')).toContainText('Chart candidates');
  await alerts.locator('summary').click();
  await expect(alerts.locator('.data-list')).toContainText('VXX RSI below 42');
  await scans.getByRole('button',{name:'Load saved scan'}).click();
  await expect(page.locator('.screener-results tbody tr[data-symbol]')).toHaveCount(1);
  await expect(page.locator('.screener-results tbody tr[data-symbol="COIN"]')).toBeVisible();
  await expect(page.getByText(/Showing saved scan snapshot:/)).toContainText('archived values');
});
