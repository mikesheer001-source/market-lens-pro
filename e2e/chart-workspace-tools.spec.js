import {test,expect} from './market-fixture.js';

const row=(page,key)=>page.locator('#chart-lab-panel [data-chart-workspace-row="'+key+'"]');
const panel=(page,key)=>page.locator('#chart-workspaces > [data-workspace-section="'+key+'"]');
const chart=page=>page.locator('#price-chart');
async function configure(page,choices){
  await page.locator('.chart-tools summary').click();
  await page.getByRole('button',{name:'Workspace tools & overlays',exact:true}).click();
  const dialog=page.locator('#chart-workspace-dialog');
  await expect(dialog).toBeVisible();
  for(const [key,enabled] of Object.entries(choices))
    await dialog.locator('[data-chart-workspace-choice="'+key+'"]').setChecked(enabled);
  await dialog.getByRole('button',{name:'Apply visibility'}).click();
  await expect(dialog).not.toBeVisible();
}
async function chooseSymbol(page,symbol){
  await page.locator('[data-action="chart-symbol-picker"]').click();
  const dialog=page.locator('#chart-symbol-dialog');
  await dialog.getByLabel('Search chart symbols').fill(symbol);
  await dialog.locator('[data-action="chart-choose-symbol"][data-symbol="'+symbol+'"]').click();
}
test('chart tools opt in, edit the shared watchlist, load archived scans, run backtest and persist visibility',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('./');
  await page.locator('tr[data-symbol="VXX"] button.star').click();
  await page.locator('[data-option="preset"]').selectOption('oversold');
  await page.locator('[data-option="matches"]').check();
  await page.locator('[data-input="scan-name"]').fill('Archived oversold');
  await page.locator('[data-action="save-scan"]').click();
  const scanId=await page.locator('[data-option="saved-scan-select"] option').last().getAttribute('value');
  await page.locator('.sidebar [data-tab="charts"]').click();
  await expect(page.locator('.chart-workspace-controls')).toHaveCount(0);
  await expect(page.locator('#chart-workspaces > details')).toHaveCount(9);
  await configure(page,{watchlist:true,scan:true,backtest:true,scripts:true,data:true});
  await expect(page.locator('#chart-lab-panel [data-chart-workspace-row]')).toHaveCount(5);
  const ticker=await page.locator('[data-action="chart-symbol-picker"]').getAttribute('data-symbol');
  const star=row(page,'watchlist').locator('[data-action="chart-workspace-star"]');
  const prior=await star.getAttribute('aria-pressed');
  await star.click();
  await expect(star).toHaveAttribute('aria-pressed',String(prior!=='true'));
  await row(page,'watchlist').getByLabel('Jump to watchlist symbol').selectOption('VXX');
  await expect(page.locator('[data-action="chart-symbol-picker"]')).toHaveAttribute('data-symbol','VXX');
  await row(page,'scan').getByLabel('Chart saved scan').selectOption(scanId);
  await expect(row(page,'scan')).toContainText('Archived Archived oversold');
  await expect(row(page,'scan')).toContainText('(not live)');
  await expect(panel(page,'screener')).not.toHaveAttribute('open','');
  await row(page,'scan').getByLabel('Chart saved scan').selectOption('');
  await expect(row(page,'scan')).toContainText('Current rules');
  await chooseSymbol(page,ticker);
  await row(page,'backtest').getByRole('button',{name:'Run on chart'}).click();
  await expect.poll(async()=>Number(await chart(page).getAttribute('data-workspace-trade-markers'))).toBeGreaterThan(0);
  const markerCount=await chart(page).getAttribute('data-workspace-trade-markers');
  await expect(panel(page,'backtest')).not.toHaveAttribute('open','');
  await configure(page,{trades:false,watchlist:false});
  await expect(chart(page)).toHaveAttribute('data-workspace-trade-markers','0');
  await expect(row(page,'watchlist')).toHaveCount(0);
  await row(page,'backtest').getByRole('button',{name:'Settings',exact:true}).click();
  await expect(panel(page,'backtest')).toHaveAttribute('open','');
  await expect(panel(page,'backtest').locator('#equity-chart canvas').first()).toBeVisible();
  await configure(page,{trades:true});
  await expect(chart(page)).toHaveAttribute('data-workspace-trade-markers',markerCount);
  await row(page,'scripts').getByRole('button',{name:'Script Lab'}).click();
  await expect(panel(page,'scripts')).toHaveAttribute('open','');
  await panel(page,'scripts').locator('[data-action="pine-example"][data-example="rsi-indicator"]').click();
  await panel(page,'scripts').locator('[data-action="pine-run"]').click();
  await expect(chart(page)).toHaveAttribute('data-workspace-pine-scripts','1');
  await configure(page,{pine:false});
  await expect(chart(page)).toHaveAttribute('data-workspace-pine-scripts','0');
  await page.reload();
  await expect(row(page,'watchlist')).toHaveCount(0);
  await expect(row(page,'scan')).toBeVisible();
  await expect(chart(page)).toHaveAttribute('data-workspace-pine-scripts','0');
  await configure(page,{pine:true});
  await expect(chart(page)).toHaveAttribute('data-workspace-pine-scripts','1');
  await expect(row(page,'data')).toContainText('Alpaca IEX');
  await expect(page.locator('.sidebar [data-tab="backtest"]')).toBeVisible();
  await expect(page.locator('#chart-workspaces > details')).toHaveCount(9);
  expect(errors).toEqual([]);
});
test('price alert and option strike overlays are independent, symbol-specific and update from the builder',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('./');
  await page.locator('.sidebar [data-tab="charts"]').click();
  await chooseSymbol(page,'SPY');
  await configure(page,{alerts:true,options:true,alertLevels:true,strikes:true});
  await row(page,'alerts').getByLabel('Chart alert price').fill('450');
  await row(page,'alerts').getByLabel('Chart alert condition').selectOption('<');
  await row(page,'alerts').getByRole('button',{name:'Add price alert'}).click();
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','1');
  await row(page,'alerts').getByRole('button',{name:'Manage'}).click();
  await expect(panel(page,'alerts')).toContainText('SPY PRICE below 450.00');
  await row(page,'options').getByRole('button',{name:'Open builder'}).click();
  const builder=panel(page,'options');
  await builder.getByLabel('Underlying reference price').fill('450');
  await builder.getByRole('button',{name:'+ Buy Call',exact:true}).click();
  await expect(builder.getByLabel('Leg 1 strike',{exact:true})).toHaveValue('450');
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','1');
  await builder.getByRole('button',{name:'+ Sell Put',exact:true}).click();
  await builder.getByLabel('Leg 2 strike',{exact:true}).fill('460');
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','2');
  await expect(row(page,'options')).toContainText('2 strike levels');
  await configure(page,{strikes:false});
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','0');
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','1');
  await expect(builder.getByLabel('Leg 2 strike',{exact:true})).toHaveValue('460');
  await configure(page,{strikes:true,alertLevels:false});
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','2');
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','0');
  await chooseSymbol(page,'VXX');
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','0');
  await expect(row(page,'options')).toContainText('no strikes for VXX');
  await configure(page,{alertLevels:true});
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','0');
  await chooseSymbol(page,'SPY');
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','2');
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','1');
  await panel(page,'options').locator(':scope > summary').click();
  await expect(chart(page)).toHaveAttribute('data-workspace-strike-levels','2');
  await panel(page,'alerts').getByRole('button',{name:'Remove alert'}).click();
  await expect(chart(page)).toHaveAttribute('data-workspace-alert-levels','0');
  expect(errors).toEqual([]);
});
test.describe('mobile chart controls',()=>{
  test.use({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  test('optional chart rows fit the phone and remain available in fullscreen',async({page})=>{
    await page.goto('./');
    await page.locator('.mobile-nav [data-tab="charts"]').click();
    await configure(page,{watchlist:true,scan:true,backtest:true,alerts:true,options:true,scripts:true,data:true});
    await expect(page.locator('#chart-lab-panel [data-chart-workspace-row]')).toHaveCount(7);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(391);
    await page.getByRole('button',{name:'Fullscreen',exact:true}).click();
    await expect(page.locator('#chart-lab-panel')).toHaveAttribute('data-fullscreen','true');
    await expect(page.locator('.chart-workspace-controls')).toBeVisible();
    await configure(page,{watchlist:false,scan:false,backtest:false,alerts:false,options:false,scripts:false,data:false});
    await expect(page.locator('.chart-workspace-controls')).toHaveCount(0);
    await expect(chart(page).locator('canvas').first()).toBeVisible();
    await page.getByRole('button',{name:'Exit fullscreen',exact:true}).click();
    await expect(page.locator('#chart-workspaces > details')).toHaveCount(9);
  });
});
