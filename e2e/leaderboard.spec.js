import {test,expect} from '@playwright/test';

test('all five presets compare on one symbol, sort by all columns and load best trade history',async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('./');
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await expect(page.getByRole('button',{name:'Compare all strategies'})).toBeVisible();
  await page.locator('[data-action="compare-strategies"]').first().click();
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(12);
  await expect(page.locator('.leaderboard-table tr.leaderboard-best')).toHaveCount(1);
  await expect(page.locator('.leaderboard-table th[aria-sort="descending"]')).toContainText('Sharpe');
  await expect(page.locator('#leaderboard-chart canvas').first()).toBeVisible();
  await expect(page.locator('.leaderboard-legend .leaderboard-legend-item')).toHaveCount(4);
  await expect(page.locator('#leaderboard-source')).toContainText('SIMULATED Demo OHLCV');
  await page.locator('[data-action="sort-leaderboard"][data-key="returnPct"]').click();
  await expect(page.locator('.leaderboard-table th[aria-sort="descending"]')).toContainText('Total return');
  await page.locator('[data-action="sort-leaderboard"][data-key="maxDD"]').click();
  await expect(page.locator('.leaderboard-table th[aria-sort="ascending"]')).toContainText('Max DD');
  await page.locator('[data-action="sort-leaderboard"][data-key="name"]').click();
  await expect(page.locator('.leaderboard-table th[aria-sort="ascending"]')).toContainText('Strategy');
  await page.locator('[data-action="load-best-strategy"]').click();
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(12);
  const metrics=await page.locator('.leaderboard-best td').allTextContents();
  expect(metrics.join(' ')).toContain('Best Sharpe');
  await expect(page.locator('.panel').filter({has:page.getByRole('heading',{name:'Trade log'})})).toBeVisible();
  expect(errors).toEqual([]);
});

test('saved Pine strategy is included, indicator-only script is disclosed and overlays persist on reload',async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('./');
  await page.locator('.sidebar [data-tab="scripts"]').click();
  await page.locator('[data-action="pine-example"][data-example="ema-cross"]').click();
  await page.locator('#pine-name').fill('Saved crossover comparison');
  await page.locator('[data-action="pine-save"]').click();
  await page.locator('[data-action="pine-example"][data-example="rsi-indicator"]').click();
  await page.locator('#pine-name').fill('Saved RSI indicator');
  await page.locator('[data-action="pine-save"]').click();
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await page.locator('[data-action="compare-strategies"]').first().click();
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(13);
  await expect(page.locator('.leaderboard-table')).toContainText('Saved crossover comparison');
  await expect(page.getByText(/scripts unavailable:/)).toContainText('Saved RSI indicator');
  await expect(page.locator('#leaderboard-chart canvas').first()).toBeVisible();
  await page.locator('.sidebar [data-tab="charts"]').click();
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(13);
  await page.reload();
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(13);
  await expect(page.locator('#leaderboard-chart canvas').first()).toBeVisible();
  await page.locator('[data-action="load-best-strategy"]').click();
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  expect(errors).toEqual([]);
});

test('returning to each symbol restores that symbol’s strategy, leaderboard and equity after reload',async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('./');
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await page.locator('[data-bt="strategy"]').selectOption('ema-cross');
  await page.locator('[data-action="run-backtest"]').click();
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  await page.locator('[data-action="compare-strategies"]').first().click();
  await expect(page.locator('#leaderboard-source')).toContainText('DEMO-SPY');
  await page.locator('[data-option="symbol"]').selectOption('DEMO-VXX');
  await expect(page.locator('.leaderboard-table tbody tr')).toHaveCount(0);
  await page.locator('[data-bt="strategy"]').selectOption('breakout');
  await page.locator('[data-action="run-backtest"]').click();
  await page.locator('[data-action="compare-strategies"]').first().click();
  await expect(page.locator('#leaderboard-source')).toContainText('DEMO-VXX');
  await page.locator('[data-option="symbol"]').selectOption('DEMO-SPY');
  await expect(page.locator('[data-bt="strategy"]')).toHaveValue('ema-cross');
  await expect(page.locator('#leaderboard-source')).toContainText('DEMO-SPY');
  await expect(page.locator('#equity-chart canvas').first()).toBeVisible();
  await page.locator('[data-option="symbol"]').selectOption('DEMO-VXX');
  await expect(page.locator('[data-bt="strategy"]')).toHaveValue('breakout');
  await expect(page.locator('#leaderboard-source')).toContainText('DEMO-VXX');
  await page.reload();
  await page.locator('.sidebar [data-tab="backtest"]').click();
  await page.locator('[data-option="symbol"]').selectOption('DEMO-VXX');
  await expect(page.locator('[data-bt="strategy"]')).toHaveValue('breakout');
  await expect(page.locator('#leaderboard-chart canvas').first()).toBeVisible();
  await page.locator('[data-option="symbol"]').selectOption('DEMO-SPY');
  await expect(page.locator('[data-bt="strategy"]')).toHaveValue('ema-cross');
  await expect(page.locator('#leaderboard-chart canvas').first()).toBeVisible();
  expect(errors).toEqual([]);
});
